const assert=require('assert/strict');
const {forecast,finishLesson,freshState,grantRewards,streak}=require('./compiled/planner.js');
const lessons=require('../data/lessons.json');
const cfg={deadline:'2026-10-29',weekdayMinutes:75,weekendMinutes:120,daysOff:[],reminderHour:20,reminderMinute:0,wpm:75};
const now=new Date(2026,9,25,10);
const old=forecast(lessons,freshState(),cfg,now);
assert.equal(old.total,113);
assert.ok(old.remainingMinutes>1400);
assert.equal(old.status,'at-risk');
assert.ok(old.shortfall>0);
assert.ok(old.extraDaily>0);
const first=finishLesson(freshState(),lessons[0].id,now);
assert.equal(first.state.xp,15);
assert.equal(finishLesson(first.state,lessons[0].id,now).xpGained,0);
const after=forecast(lessons,first.state,cfg,now);
assert.equal(after.finished,1);
assert.ok(after.remainingMinutes<old.remainingMinutes);
const more={...cfg,weekdayMinutes:600,weekendMinutes:600};
const enough=forecast(lessons,first.state,more,now);
assert.equal(enough.status,'on-track');
assert.equal(streak(first.state,now),1);
const missed=forecast(lessons,freshState(),cfg,new Date(2026,9,31,10));
assert.equal(missed.status,'expired');
const allState={...freshState(),done:Object.fromEntries(lessons.map(l=>[l.id,{at:now.toISOString(),seconds:100}]))};
const completed=forecast(lessons,allState,cfg,now);assert.equal(completed.status,'complete');
const award=grantRewards(allState,lessons,cfg,completed,now);
assert.equal(award.xpGained,250);
assert.equal(grantRewards(award.state,lessons,cfg,completed,now).xpGained,0);
console.log('PASS — 113 lessons imported, at-risk detected, no skip, reschedule, rewards dedup, past deadline, streak');
