const assert=require('node:assert/strict');
const {makeQuizSnapshot,restoreQuizSnapshot,quizRemainingSeconds,unansweredCount}=require('./compiled/quizSession.js');
const bank=require('../data/questions.json').questions;
const sample=bank.slice(0,3),start=Date.now()-120_000;
const snap=makeQuizSnapshot({mode:'exam',questions:sample,start},{[sample[0].id]:sample[0].a},2);
const restored=restoreQuizSnapshot(snap,bank);
assert.equal(restored.session.start,start);
assert.deepEqual(restored.session.questions.map(q=>q.id),sample.map(q=>q.id));
assert.equal(restored.index,2);
assert.deepEqual(restored.answers,{[sample[0].id]:sample[0].a});
assert.equal(quizRemainingSeconds(start,start+120_000),3480);
assert.equal(quizRemainingSeconds(start,start+3700_000),0);
assert.equal(unansweredCount(sample,restored.answers),2);
assert.equal(restoreQuizSnapshot({...snap,questionIds:['bogus']},bank),null);
assert.equal(restoreQuizSnapshot({...snap,questionIds:[sample[0].id,sample[0].id]},bank),null);
assert.equal(restoreQuizSnapshot({...snap,start:Date.now()+300000},bank),null);
const bogus=restoreQuizSnapshot({...snap,answers:{[sample[0].id]:200},index:999},bank);
assert.deepEqual(bogus.answers,{});assert.equal(bogus.index,2);
console.log('PASS — resume quiz, preserve timed start, reject corrupt snapshots, enforce timer and unanswered count');
