const assert=require('node:assert/strict');
const {buildJourney,splitLessonSteps,challengePassed,awardMilestone}=require('./compiled/journey.js');
const {freshState}=require('./compiled/planner.js');
const {emptyQuizProgress,drawLessonPractice,awardLessonMastery}=require('./compiled/quiz.js');
const lessons=require('../data/lessons.json');const questions=require('../data/questions.json').questions;
let study=freshState();let quiz=emptyQuizProgress();
const units=buildJourney(lessons,questions,study,quiz);
assert.equal(units.length,15);
assert.equal(units.reduce((a,u)=>a+u.total,0),113);
assert.equal(units.flatMap(u=>u.stages).filter(s=>s.kind==='lesson').length,113);
assert.equal(units.flatMap(u=>u.stages).filter(s=>s.status==='active').length,1);
assert.equal(units.flatMap(u=>u.stages).filter(s=>s.status==='done').length,0);
const basics=units.find(u=>u.topic==='basics');assert.equal(basics.hasChallenge,false);
assert.equal(basics.stages.every(s=>s.kind==='lesson'),true);
const focus=lessons[0];const segments=splitLessonSteps(focus.reading,850);assert.ok(segments.length>1);
assert.equal(segments.join('\n\n'),focus.reading.trim().replace(/\r\n/g,'\n').split(/\n\s*\n/).map(x=>x.trim()).filter(Boolean).join('\n\n'));
study.done[focus.id]={at:'2026-10-25T10:00:00Z',seconds:300};
const next=buildJourney(lessons,questions,study,quiz).find(u=>u.topic===focus.topic);
assert.equal(next.stages[0].status,'done');assert.equal(next.stages[1].status,'active');
assert.equal(challengePassed(4,5),true);assert.equal(challengePassed(3,5),false);assert.equal(challengePassed(0,0),false);
let r=awardMilestone(quiz,'risk',true);assert.equal(r.xp,40);
let repeat=awardMilestone(r.progress,'risk',true);assert.equal(repeat.xp,0);
let failed=awardMilestone(repeat.progress,'aml',false);assert.equal(failed.xp,0);
const linked=lessons.find(l=>l.questions.length>=5);const linkedQuiz=drawLessonPractice(questions,linked.questions,5,()=>0.3);assert.equal(linkedQuiz.length,5);assert.ok(linkedQuiz.every(q=>linked.questions.includes(q.id)));
const mastered=awardLessonMastery(quiz,linked.id,true);assert.equal(mastered.xp,20);assert.equal(awardLessonMastery(mastered.progress,linked.id,true).xp,0);
console.log('PASS — 15 journey units, 113 lesson nodes, progression, no-question topic, reading segments, 80% challenge, once-only +40 XP');
