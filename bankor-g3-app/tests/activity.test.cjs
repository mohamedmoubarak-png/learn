const assert=require('node:assert/strict');
const {activitySummary}=require('./compiled/activity.js');
const {freshState}=require('./compiled/planner.js');
const at=(d)=>`${d}T12:00:00.000Z`;
const now=new Date('2026-10-25T11:00:00Z');
const s=freshState();
const empty=activitySummary(s,[],now);
assert.equal(empty.streak,0);assert.equal(empty.activeToday,false);
const a=[{id:'q1',date:at('2026-10-23'),total:10},{id:'q2',date:at('2026-10-24'),total:5}];
const yesterday=activitySummary(s,a,now);
assert.equal(yesterday.streak,2);assert.equal(yesterday.activeToday,false);
const today=activitySummary(s,[...a,{id:'q3',date:at('2026-10-25'),total:7}],now);
assert.equal(today.streak,3);assert.equal(today.questionsToday,7);assert.equal(today.activeToday,true);
const withLesson={...s,done:{l1:{at:at('2026-10-25'),seconds:360}}};
assert.equal(activitySummary(withLesson,a,now).streak,3);
assert.equal(activitySummary(withLesson,a,now).lessonsToday,1);
assert.equal(activitySummary(s,[...a,{id:'zero',date:at('2026-10-25'),total:0}],now).streak,2);
assert.equal(activitySummary(s,[{id:'x',date:at('2026-10-22'),total:4}],now).streak,0);
console.log('PASS — quiz and lessons both count for daily streak, no duplicate days or zero-question activity');
